/*
 * 실행 위치: 이 전달 모듈의 최상위 폴더
 * 목적: 기존 H2 DB의 다른 데이터를 지우지 않고 W01~W05와 농장 20곳을 병합
 * 기준 키: warehouse_code, farm_code
 */

MERGE INTO WAREHOUSE (
    ACTIVE,
    ADDRESS,
    WAREHOUSE_CODE,
    DISPLAY_ORDER,
    NAME,
    OPERATION_FOCUS,
    SERVICE_AREA,
    LATITUDE,
    LONGITUDE
)
KEY (WAREHOUSE_CODE)
SELECT
    CAST(ACTIVE AS BOOLEAN),
    ADDRESS,
    WAREHOUSE_CODE,
    CAST(DISPLAY_ORDER AS INTEGER),
    NAME,
    OPERATION_FOCUS,
    SERVICE_AREA,
    CAST(LATITUDE AS DOUBLE PRECISION),
    CAST(LONGITUDE AS DOUBLE PRECISION)
FROM CSVREAD(
    'data/warehouses.csv',
    NULL,
    'charset=UTF-8 fieldSeparator=,'
);

MERGE INTO FARM_CUSTOMER (
    ADDRESS,
    ANIMAL_TYPE,
    CREATED_AT,
    DEMO_DATA,
    DISTANCE_KM,
    FARM_CODE,
    FARM_NAME,
    LATITUDE,
    LIVESTOCK_COUNT,
    LONGITUDE,
    MONTHLY_FEED_QUANTITY,
    NOTES,
    PHONE,
    POSTAL_CODE,
    PREFERRED_FEED,
    RECURRING_DELIVERY_DAY,
    REPRESENTATIVE_NAME,
    STATUS,
    WAREHOUSE_ID
)
KEY (FARM_CODE)
SELECT
    C.ADDRESS,
    C.ANIMAL_TYPE,
    CAST(C.CREATED_AT AS TIMESTAMP),
    CAST(C.DEMO_DATA AS BOOLEAN),
    CAST(C.DISTANCE_KM AS DOUBLE PRECISION),
    C.FARM_CODE,
    C.FARM_NAME,
    CAST(C.LATITUDE AS DOUBLE PRECISION),
    CAST(C.LIVESTOCK_COUNT AS INTEGER),
    CAST(C.LONGITUDE AS DOUBLE PRECISION),
    CAST(C.MONTHLY_FEED_QUANTITY AS INTEGER),
    C.NOTES,
    C.PHONE,
    C.POSTAL_CODE,
    C.PREFERRED_FEED,
    CAST(C.RECURRING_DELIVERY_DAY AS INTEGER),
    C.REPRESENTATIVE_NAME,
    C.STATUS,
    (
        SELECT W.WAREHOUSE_ID
        FROM WAREHOUSE W
        WHERE W.WAREHOUSE_CODE = C.ASSIGNED_WAREHOUSE_CODE
    )
FROM CSVREAD(
    'data/farm_customers.csv',
    NULL,
    'charset=UTF-8 fieldSeparator=,'
) C;
